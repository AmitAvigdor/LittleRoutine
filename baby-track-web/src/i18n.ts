export function getSystemLanguage(): AppLanguage {
  if (typeof navigator !== 'undefined') {
    const language = navigator.language || navigator.languages?.[0] || '';
    if (language.toLowerCase().startsWith('he')) {
      return 'he';
    }
  }

  return 'en';
}

export function resolveLanguagePreference(preference?: LanguagePreference | null): AppLanguage {
  if (preference === 'he' || preference === 'en') {
    return preference;
  }

  return getSystemLanguage();
}

export function isRtlLanguage(language: AppLanguage | string): boolean {
  return language.toLowerCase().startsWith('he');
}

export function applyDocumentLanguage(language: AppLanguage | string): void {
  if (typeof document === 'undefined') return;

  const resolvedLanguage: AppLanguage = isRtlLanguage(language) ? 'he' : 'en';
  document.documentElement.lang = resolvedLanguage;
  document.documentElement.dir = isRtlLanguage(resolvedLanguage) ? 'rtl' : 'ltr';
}

export async function changeAppLanguage(preference?: LanguagePreference | null): Promise<AppLanguage> {
  const language = resolveLanguagePreference(preference);
  await i18n.changeLanguage(language);
  applyDocumentLanguage(language);
  return language;
}

